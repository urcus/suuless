"""Small DB-API boundary: SQLite by default, optional external PostgreSQL.

Application SQL uses qmark parameters and rows addressable by name or position.
PostgreSQL reads are autocommitted (including SSE); write contexts explicitly
serialize with a transaction advisory lock, preserving SQLite writer semantics.
"""
from decimal import Decimal
from pathlib import Path
import re
import sqlite3

# One lock per database, shared by startup, migration and application writers.
WRITE_LOCK = 731901047
IntegrityError = sqlite3.IntegrityError
DatabaseError = sqlite3.Error


def is_postgres(database):
    return str(database).startswith(('postgresql://', 'postgres://'))


def configured_database(config):
    url = config.get('DATABASE_URL', '').strip()
    if url and not is_postgres(url):
        raise ValueError('DATABASE_URL must be a postgresql:// or postgres:// URL')
    return url or config['DATABASE']


class Row(dict):
    def __getitem__(self, key):
        if isinstance(key, (int, slice)):
            return tuple(self.values())[key]
        return super().__getitem__(key)


def row_factory(cursor):
    columns = [column.name for column in (cursor.description or [])]
    def row(values):
        # SUM(bigint) returns numeric in PostgreSQL, but API quantities stay integers.
        return Row(zip(columns, (int(v) if isinstance(v, Decimal) and v == v.to_integral_value() else v for v in values)))
    return row


def parameters(sql):
    """Convert only placeholders outside SQL string/identifier literals."""
    parts = re.split(r"('(?:[^']|'')*'|\"(?:[^\"]|\"\")*\")", sql)
    return ''.join(part.replace('%', '%%').replace('?', '%s') if i % 2 == 0 else part.replace('%', '%%')
                   for i, part in enumerate(parts))


class PostgresConnection:
    def __init__(self, database, timeout):
        import psycopg
        self.driver = psycopg
        try:
            self.connection = psycopg.connect(database, autocommit=True, connect_timeout=timeout,
                                               row_factory=row_factory)
            self.connection.execute("SELECT set_config('search_path', 'public', false)")
            self.connection.execute("SELECT set_config('lock_timeout', %s, false)", (str(timeout * 1000),))
        except psycopg.Error:
            if hasattr(self, 'connection'):
                self.connection.close()
            raise sqlite3.OperationalError('PostgreSQL connection failed; check connectivity, TLS and credentials') from None
        self.in_transaction = False

    def begin(self):
        if not self.in_transaction:
            self.connection.execute('BEGIN')
            self.in_transaction = True
            try:
                self.connection.execute('SELECT pg_advisory_xact_lock(%s)', (WRITE_LOCK,))
            except self.driver.Error:
                self.rollback()
                raise sqlite3.OperationalError('PostgreSQL write lock unavailable') from None

    def execute(self, sql, values=()):
        if sql.strip().upper() == 'BEGIN IMMEDIATE':
            self.begin()
            return self.connection.cursor()
        if sql.lstrip().upper().startswith('ALTER TABLE '):
            sql = re.sub(r'\bINTEGER\b', 'BIGINT', sql)
        try:
            return self.connection.execute(parameters(sql), values)
        except self.driver.IntegrityError:
            raise IntegrityError('Database constraint violation') from None
        except self.driver.Error:
            # Never expose connection strings, statement parameters or row contents.
            raise DatabaseError('PostgreSQL operation failed') from None

    def executescript(self, schema):
        self.begin()
        schema = schema.replace('PRAGMA journal_mode=WAL;', '')
        schema = re.sub(r'\bINTEGER\b', 'BIGINT', schema)
        schema = re.sub(r'\bid BIGINT PRIMARY KEY', 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', schema)
        schema = schema.replace(' REAL ', ' DOUBLE PRECISION ')
        schema = schema.replace('lower(hex(randomblob(16)))', "replace(gen_random_uuid()::text, '-', '')")
        for statement in schema.split(';'):
            if statement.strip():
                self.execute(statement)

    def commit(self):
        self.connection.commit()
        self.in_transaction = False

    def rollback(self):
        self.connection.rollback()
        self.in_transaction = False

    def close(self):
        self.connection.close()

    def __enter__(self):
        self.begin()
        return self

    def __exit__(self, kind, error, traceback):
        if kind:
            self.rollback()
        else:
            self.commit()


def connect(database, timeout=15):
    if is_postgres(database):
        return PostgresConnection(database, timeout)
    conn = sqlite3.connect(database, timeout=timeout)
    conn.row_factory = sqlite3.Row
    conn.execute('PRAGMA foreign_keys=ON')
    return conn


def columns(conn, table):
    # Table identifiers originate only in schema/migration code, never HTTP input.
    if not re.fullmatch('[a-z_]+', table):
        raise ValueError('Invalid table identifier')
    if isinstance(conn, PostgresConnection):
        return [r[0] for r in conn.execute('SELECT column_name FROM information_schema.columns WHERE table_schema=? AND table_name=? ORDER BY ordinal_position', ('public', table))]
    return [r[1] for r in conn.execute(f'PRAGMA table_info({table})')]  # nosec B608


def prepare_directory(database):
    if not is_postgres(database):
        Path(database).parent.mkdir(parents=True, exist_ok=True)
